# ── Endpoint 1: Generate ticket from free text ──────────────────────────────
@app.post("/generate-ticket")
async def generate_ticket(payload: TextInput):
    """
    User types a description in plain English or a greeting.
    Returns a polite greeting response or a full ticket preview generated by GPT-4o-mini.
    """
    if not payload.user_text.strip():
        raise HTTPException(status_code=400, detail="Input text cannot be empty.")
    try:
        result = generate_ticket_from_text(payload.user_text)
        return {
            "success": True,
            "is_greeting": result.get("is_greeting", False),
            "greeting_message": result.get("greeting_message", ""),
            "is_multi_ticket": result.get("is_multi_ticket", False),
            "ticket": result.get("ticket"),
            "tickets": result.get("tickets")
        }
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"AI generation failed: {str(e)}")


# ── Endpoint 2: Apply user changes to ticket preview ────────────────────────
@app.post("/update-preview")
async def update_preview(payload: ChangeRequest):
    """
    User says what they want to change in the preview.
    Returns updated ticket with changes applied.
    """
    if not payload.feedback.strip():
        raise HTTPException(status_code=400, detail="Feedback cannot be empty.")
    try:
        updated = apply_changes_to_ticket(payload.current_ticket.dict(), payload.feedback)
        return {"success": True, "ticket": updated}
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Update failed: {str(e)}")


